import { isValidIdentifier } from './infer-types.js';

export function generateTypeScript(model, { source } = {}) {
  const blocks = [];
  if (model.root.kind !== 'object' || !model.root.name) {
    blocks.push(`export type ${model.rootName} = ${typeExpr(model.root)};`);
  }
  for (const node of model.declarations) {
    const lines = node.properties.map(
      (p) => `  ${propertyKey(p.key)}${p.optional ? '?' : ''}: ${typeExpr(p.type)};`,
    );
    blocks.push(`export interface ${node.name} {\n${lines.join('\n')}\n}`);
  }
  return `${header(source)}\n\n${blocks.join('\n\n')}\n`;
}

export function header(source) {
  const from = source ? ` from ${String(source).replace(/[\r\n\u2028\u2029]+/g, ' ')}` : '';
  return `// Generated by jsonforge-cli${from}.`;
}

export function propertyKey(key) {
  return isValidIdentifier(key) ? key : JSON.stringify(key);
}

function typeExpr(node) {
  switch (node.kind) {
    case 'object':
      return node.properties.length === 0 ? 'Record<string, unknown>' : node.name;
    case 'array': {
      const inner = typeExpr(node.items);
      return node.items.kind === 'union' ? `(${inner})[]` : `${inner}[]`;
    }
    case 'union':
      return node.types.map(typeExpr).join(' | ');
    default:
      return node.kind;
  }
}
