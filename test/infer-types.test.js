import { test } from 'node:test';
import assert from 'node:assert/strict';
import { buildModel, infer, toTypeName, singularize, validateTypeName } from '../src/core/infer-types.js';
import { generateTypeScript } from '../src/core/generate-typescript.js';
import { generateZod } from '../src/core/generate-zod.js';

test('infers primitives, null, nested objects and arrays', () => {
  const node = infer({ s: 'a', n: 1, b: true, z: null, o: { x: 1 }, a: [1] });
  assert.deepEqual(
    node.properties.map((p) => [p.key, p.type.kind]),
    [['s', 'string'], ['n', 'number'], ['b', 'boolean'], ['z', 'null'], ['o', 'object'], ['a', 'array']],
  );
});

test('merges multiple samples: missing keys are optional, conflicts are unions', () => {
  const model = buildModel([{ id: 1, name: 'a' }, { id: '2', extra: true }], 'Users');
  const ts = generateTypeScript(model);
  assert.match(ts, /export type Users = User\[\];/);
  assert.match(ts, /  id: string \| number;/);
  assert.match(ts, /  name\?: string;/);
  assert.match(ts, /  extra\?: boolean;/);
});

test('null mixed with a value becomes nullable', () => {
  const model = buildModel([{ v: null }, { v: 'x' }], 'Rows');
  assert.match(generateTypeScript(model), /v: string \| null;/);
  assert.match(generateZod(model), /v: z\.string\(\)\.nullable\(\),/);
});

test('empty arrays and objects produce warnings and loose types', () => {
  const model = buildModel({ list: [], meta: {}, nothing: null }, 'Root');
  assert.deepEqual(model.warnings.map((w) => w.path), ['$.list', '$.meta', '$.nothing']);
  const ts = generateTypeScript(model);
  assert.match(ts, /list: unknown\[\];/);
  assert.match(ts, /meta: Record<string, unknown>;/);
  assert.match(ts, /nothing: null;/);
});

test('empty array merged with non-empty arrays uses the known item type', () => {
  const model = buildModel([{ tags: [] }, { tags: ['a'] }], 'Posts');
  assert.match(generateTypeScript(model), /tags: string\[\];/);
  assert.deepEqual(model.warnings, []);
});

test('escapes property names that are not identifiers', () => {
  const ts = generateTypeScript(buildModel({ 'first-name': 'a', 'a"b': 1, '': 2, '1x': 3, ok_$: 4 }, 'Root'));
  assert.match(ts, /  "first-name": string;/);
  assert.match(ts, /  "a\\"b": number;/);
  assert.match(ts, /  "": number;/);
  assert.match(ts, /  "1x": number;/);
  assert.match(ts, /  ok_\$: number;/);
});

test('keeps __proto__ as a real key in Zod object literals', () => {
  const zod = generateZod(buildModel(JSON.parse('{"__proto__": 1}'), 'Root'));
  assert.match(zod, /\["__proto__"\]: z\.number\(\),/);
});

test('derives safe, unique nested type names', () => {
  assert.equal(toTypeName('first-name'), 'FirstName');
  assert.equal(toTypeName('2fa'), 'T2fa');
  assert.equal(toTypeName('string'), 'String'.concat('Type'));
  assert.equal(toTypeName('class'), 'Class');
  assert.equal(toTypeName('!!!'), 'Item');
  assert.equal(singularize('users'), 'user');
  assert.equal(singularize('categories'), 'category');
  assert.equal(singularize('status'), 'status');

  const model = buildModel({ item: { a: 1 }, nested: { item: { b: 2 } }, object: { c: 3 } }, 'Root');
  assert.deepEqual(model.declarations.map((d) => d.name), ['Root', 'Item', 'Nested', 'Item2', 'ObjectType']);
});

test('rejects reserved or invalid root names', () => {
  for (const name of ['class', 'string', 'Record', '1Abc', 'a-b', '']) {
    assert.throws(() => validateTypeName(name), { code: 'INVALID_NAME' });
  }
  assert.equal(validateTypeName('User'), 'User');
});

test('output is deterministic', () => {
  const value = [{ b: 1, a: { x: [1, 'y', null] } }, { a: { z: true } }];
  assert.equal(generateTypeScript(buildModel(value, 'Root')), generateTypeScript(buildModel(value, 'Root')));
  assert.equal(generateZod(buildModel(value, 'Root')), generateZod(buildModel(value, 'Root')));
});

test('Zod schemas are declared before they are used', () => {
  const zod = generateZod(buildModel({ a: { b: { c: 1 } } }, 'Root'));
  assert.ok(zod.indexOf('const BSchema') < zod.indexOf('const ASchema'));
  assert.ok(zod.indexOf('const ASchema') < zod.indexOf('const RootSchema'));
});

test('only Zod 4 output is supported for now', () => {
  assert.throws(() => generateZod(buildModel({ a: 1 }, 'Root'), { zodVersion: 3 }), {
    code: 'UNSUPPORTED_ZOD_VERSION',
  });
});

test('comment header cannot break out of the line comment', () => {
  const ts = generateTypeScript(buildModel({ a: 1 }, 'Root'), { source: 'x\n*/ alert(1)' });
  assert.equal(ts.split('\n')[0], '// Generated by jsonforge-cli from x */ alert(1).');
});
